"""Generate the LaTeX body of the stochastic table (and paired statistics)
straight from the campaign outputs, so that no number is transcribed by hand.

    python scripts/make_tables.py --prefix results/final_stoch > results/final_stoch_table.tex
"""
import argparse, glob, json, math, os
import numpy as np
from scipy import stats

POLS = ["static", "reactive-plan", "reactive-MWR", "reactive-SPT", "replan", "replan-opt"]
SHORT = {"static": "static", "reactive-plan": "plan-react", "reactive-MWR": "MWR", "reactive-SPT": "SPT",
         "replan": "list-replan", "replan-opt": "CP-replan"}


def cvar(x, q=0.05):
    m = max(1, int(math.ceil(q * len(x)))); return float(np.sort(x)[-m:].mean())


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--prefix", required=True); args = ap.parse_args()
    files = sorted(glob.glob(args.prefix + "_*.json"))
    print("% generated by scripts/make_tables.py from", args.prefix)
    print("% instance & ops & avail & PI cert (LCB) & " + " & ".join(SHORT[p] for p in POLS) + " & best gap\\\\")
    stat_lines = []
    for f in files:
        d = json.load(open(f)); r = d["row"]; M = {k: np.array(v) for k, v in d["makespans"].items()}
        cert = r.get("pi_cp_lcb", r["pi_ht_lcb"]); tag = "CP" if "pi_cp_lcb" in r else "HT"
        best = min(M, key=lambda k: M[k].mean())
        cells = []
        for p in POLS:
            if p not in M: cells.append("--"); continue
            v = f"{M[p].mean():.1f}"
            cells.append(f"\\textbf{{{v}}}" if p == best else v)
        gap = 100 * (M[best].mean() - cert) / cert
        name = r["instance"].replace("_", "\\_")
        print(f"{name} & {r['ops']} & {r['availability']:.2f} & {cert:.1f} ({tag}) & " + " & ".join(cells) + f" & {gap:.1f}\\,\\%\\\\")
        base = M["static"]
        for p in POLS:
            if p == "static" or p not in M: continue
            dlt = M[p] - base; nz = dlt[dlt != 0]
            w = stats.wilcoxon(nz).pvalue if len(nz) else 1.0
            stat_lines.append(f"% {r['instance']} {p:14s} vs static: {100*dlt.mean()/base.mean():+6.1f}%  "
                              f"CVaR95 {cvar(M[p]):.1f} vs {cvar(base):.1f}  wins/ties/losses "
                              f"{int((dlt<0).sum())}/{int((dlt==0).sum())}/{int((dlt>0).sum())}  Wilcoxon p={w:.1e}")
    print("\n".join(stat_lines))


if __name__ == "__main__":
    main()
